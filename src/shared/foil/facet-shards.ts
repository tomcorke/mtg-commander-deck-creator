// A card's facet shards: its own, or those of the facet printing with the same name (so the
// nonfoil Shattered Mirror twins show them too). Null for any other card.
export function findFacetShards(card: { set: string; collectorNumber: string; name?: string }) {
  const entry =
    facetShards[`${card.set}/${card.collectorNumber}`] ??
    Object.values(facetShards).find(({ name }) => name === card.name)
  return entry?.shards ?? null
}

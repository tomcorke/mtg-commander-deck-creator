/** The plural used as a theme name, e.g. Cat → Cats, Elf → Elves, Merfolk → Merfolk. */
export function creatureTypePlural(type: string) {
  if (irregularPlurals[type]) return irregularPlurals[type]
  if (sameInPlural.has(type) || /(?:folk|kin)$/.test(type)) return type
  if (/(?:s|x|ch|sh)$/.test(type)) return `${type}es`
  if (/[^aeiou]y$/.test(type)) return `${type.slice(0, -1)}ies`
  return `${type}s`
}

/** Theme name for every creature type, keyed by both the singular and plural spelling. */
export const creatureTypeThemes = new Map(
  creatureTypes.flatMap((type) => {
    const plural = creatureTypePlural(type)
    return [
      [type, plural],
      [plural, plural],
    ] as const
  }),
)
// Type names hold only letters, spaces, hyphens and apostrophes, so they need no escaping.
// Longest first, so "Time Lords" wins over a shorter overlapping name.
const creatureTypeWords = new RegExp(
  `\\b(?:${[...creatureTypeThemes.keys()]
    .sort((left, right) => right.length - left.length)
    .join('|')})\\b`,
  'g',
)

/**
 * Creature-type themes a card belongs to or cares about: its own subtypes ("Creature — Cat") and
 * capitalised type references in its text ("Cats you control", "Cat spells").
 */
export function creatureTypeTags(source: string) {
  return [
    ...new Set(
      [...source.matchAll(creatureTypeWords)].map(([word]) => creatureTypeThemes.get(word)!),
    ),
  ]
}

const singularByTheme = new Map(creatureTypes.map((type) => [creatureTypePlural(type), type]))
/** The creature type behind a theme name ("Cats" → "Cat"), or undefined for other themes. */
export const creatureTypeForTheme = (theme: string) => singularByTheme.get(theme)

/**
 * Tag on changelings and every-type cards ("is every creature type", CR 702.73a), including
 * makers and grantors of such bodies. It matches every creature-type theme without one tag per
 * type. "Choose a creature type" cards pick one type (CR 205.3e) and are often hosers, so they
 * get only the `Tribal` role tag.
 */
export const everyCreatureTypeTag = 'Changeling'
export const everyCreatureTypePattern =
  /\bchangeling\b|\b(?:is|are) (?:also )?every creature type|\b(?:is|has|have|with|and|gains?) all creature types\b/i

/** Whether a card carries a theme tag, counting every-type cards for any creature-type theme. */
export const hasTag = (card: { tags: string[] }, tag: string) =>
  card.tags.includes(tag) || (card.tags.includes(everyCreatureTypeTag) && singularByTheme.has(tag))
